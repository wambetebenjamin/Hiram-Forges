export function getArtisan(slug: string): Artisan | undefined {
  return artisans.find((artisan) => artisan.slug === slug);
}

export function artisansByRegion(region: string): Artisan[] {
  return artisans.filter((artisan) => artisan.region === region);
}

export function featuredArtisans(): Artisan[] {
  return artisans.filter((artisan) => artisan.featured);
}

export function artisanCountForRegion(region: string): number {
  return artisansByRegion(region).length;
}
